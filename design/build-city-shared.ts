/**
 * What city traffic needs, as data the server can read too (it has no venue model): the road paths (from the road
 * map) and each traffic-light pole's world matrix, in the order three.js finds them in the loaded venue.
 *
 *   npm run build:city-shared        (after build:city)
 *
 * Writes shared/city.data.ts.
 */
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { MeshoptDecoder } from 'meshoptimizer';
import { Matrix4, Quaternion, Vector3 } from 'three';
import { readFileSync, writeFileSync } from 'node:fs';

await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder });
const doc = await io.read('public/models/tracks/racing-city.runtime.glb');
const poles: number[][] = [];
doc.getRoot().getDefaultScene()!.traverse(node => {
  const instancing = node.getExtension('EXT_mesh_gpu_instancing') as { getAttribute(name: string): { getCount(): number; getElement(i: number, out: number[]): number[] } | null } | null;
  if (!instancing || !/TrafficLight/.test(node.getName() + ' ' + (node.getParentNode()?.getName() ?? ''))) return;
  const world = new Matrix4().fromArray(node.getWorldMatrix());
  const t = instancing.getAttribute('TRANSLATION'), r = instancing.getAttribute('ROTATION'), s = instancing.getAttribute('SCALE');
  // A node with several primitives becomes one instanced mesh per primitive in three.js, each with every pole.
  const copies = Math.max(1, node.getMesh()?.listPrimitives().length ?? 1);
  for (let copy = 0; copy < copies; copy++) for (let i = 0; i < (t ?? r ?? s)!.getCount(); i++) {
    const p = new Vector3(...(t ? t.getElement(i, []) : [0, 0, 0])), q = new Quaternion(...(r ? r.getElement(i, []) : [0, 0, 0, 1])), k = new Vector3(...(s ? s.getElement(i, []) : [1, 1, 1]));
    poles.push(new Matrix4().compose(p, q, k).premultiply(world).elements.map(n => Math.round(n * 10000) / 10000));
  }
});
const paths = JSON.parse(readFileSync('public/models/tracks/racing-city.map.json', 'utf8')).paths;
writeFileSync('shared/city.data.ts', `// Generated by design/build-city-shared.ts - do not edit.\n/* eslint-disable */\n/** Road centre lines (x, y, z per point) with their district, width and whether they loop. */\nexport const CITY_ROADS: { name: string; district: string; width: number; closed: boolean; points: number[][] }[] = ${JSON.stringify(paths)};\n/** World matrix of each traffic-light pole in the city (column-major, as THREE.Matrix4.elements). */\nexport const CITY_SIGNAL_POLES: number[][] = ${JSON.stringify(poles)};\n`);
console.log(`wrote shared/city.data.ts (${paths.length} roads, ${poles.length} poles)`);
